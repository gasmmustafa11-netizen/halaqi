export function normalizeIraq(t: string): string {
  let s = (t || '').toString();
  s = s.replace(/[\u064b-\u065F\u0670\u0640]/g, '');
  s = s.replace(/\u0629/g, '\u0647');
  s = s.replace(/[\u0623\u0625\u0622]/g, '\u0627');
  s = s.replace(/[\u200F\u200E]/g, '');
  s = s.trim();
  return s;
}

